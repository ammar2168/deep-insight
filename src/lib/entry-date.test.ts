describe("parseCasualDate", () => {
	it("reads the formats a person actually types", () => {
		expect(parseCasualDate("2 Sep 2024", TODAY)).toBe("2024-09-02");
		expect(parseCasualDate("Sep 2 2024", TODAY)).toBe("2024-09-02");
		expect(parseCasualDate("September 2nd, 2024", TODAY)).toBe("2024-09-02");
		expect(parseCasualDate("2nd September 2024", TODAY)).toBe("2024-09-02");
		expect(parseCasualDate("12 August 2024", TODAY)).toBe("2024-08-12");
	});

	it("with no year, takes the most recent occurrence rather than this year", () => {
		// Today is 25 Sep 2026, so "3 Sep" is this year and "3 Oct" is last.
		expect(parseCasualDate("3 Sep", TODAY)).toBe("2026-09-03");
		expect(parseCasualDate("3 Oct", TODAY)).toBe("2025-10-03");
	});

	it("rejects what it can't be sure of", () => {
		expect(parseCasualDate("Someday", TODAY)).toBeNull();
		expect(parseCasualDate("Smarch 3 2024", TODAY)).toBeNull();
		expect(parseCasualDate("31 Feb 2024", TODAY)).toBeNull();
		expect(parseCasualDate("32 Aug 2024", TODAY)).toBeNull();
		expect(parseCasualDate("", TODAY)).toBeNull();
	});
});

describe("filenameDate", () => {
	it("ignores the capture date a camera puts in the name", () => {
		// The exact production incident: 50 pages photographed in one sitting,
		// every filename carrying that day, all merged into a single entry.
		expect(filenameDate("IMG_20260925_0001.jpg", TODAY)).toEqual({
			date: null,
			reason: "none",
		});
		expect(filenameDate("PXL_20260925_182233123.jpg", TODAY)).toEqual({
			date: null,
			reason: "none",
		});
		expect(
			filenameDate("Screenshot 2026-09-25 at 21.10.33.png", TODAY),
		).toEqual({ date: null, reason: "none" });
		expect(
			filenameDate("WhatsApp Image 2026-09-25 at 21.10.33.jpeg", TODAY),
		).toEqual({ date: null, reason: "none" });
	});

	it("trusts a name a person chose", () => {
		expect(filenameDate("2024-08-12.jpg", TODAY)).toEqual({
			date: "2024-08-12",
			source: "filename",
		});
		expect(filenameDate("20240812.png", TODAY)).toEqual({
			date: "2024-08-12",
			source: "filename",
		});
		expect(filenameDate("12 Aug 2024.jpeg", TODAY)).toEqual({
			date: "2024-08-12",
			source: "filename",
		});
		expect(filenameDate("2024_08_12.HEIC", TODAY)).toEqual({
			date: "2024-08-12",
			source: "filename",
		});
	});

	it("asks rather than picking one of two dates", () => {
		expect(filenameDate("2024-08-12 to 2024-08-14.jpg", TODAY)).toEqual({
			date: null,
			reason: "ambiguous-filename",
		});
	});

	it("is fine with the same date written twice", () => {
		expect(filenameDate("2024-08-12 (2024-08-12).jpg", TODAY)).toEqual({
			date: "2024-08-12",
			source: "filename",
		});
	});

	it("refuses impossible, future and ancient dates", () => {
		expect(filenameDate("2024-02-30.jpg", TODAY).date).toBeNull();
		expect(filenameDate("2031-01-01.jpg", TODAY).date).toBeNull();
		expect(filenameDate("1899-01-01.jpg", TODAY).date).toBeNull();
	});

	it("finds nothing in a name that has nothing", () => {
		expect(filenameDate("vacation_photo_final.jpg", TODAY)).toEqual({
			date: null,
			reason: "none",
		});
		expect(filenameDate("page 3.jpg", TODAY).date).toBeNull();
	});

	it("handles names with no extension or several dots", () => {
		expect(filenameDate("2024-08-12", TODAY).date).toBe("2024-08-12");
		expect(filenameDate("journal.2024-08-12.jpg", TODAY).date).toBe(
			"2024-08-12",
		);
	});
});

describe("pageDate", () => {
	it("uses the one date the page is headed with", () => {
		expect(pageDate([{ resolvedDate: "2024-08-12" }], TODAY)).toEqual({
			date: "2024-08-12",
			source: "page",
		});
	});

	it("treats the same date mentioned twice as one date", () => {
		expect(
			pageDate(
				[{ resolvedDate: "2024-08-12" }, { resolvedDate: "2024-08-12" }],
				TODAY,
			),
		).toEqual({ date: "2024-08-12", source: "page" });
	});

	it("won't choose between two different dates on one page", () => {
		expect(
			pageDate(
				[{ resolvedDate: "2024-08-12" }, { resolvedDate: "2024-08-14" }],
				TODAY,
			),
		).toEqual({ date: null, reason: "ambiguous-page" });
	});

	it("drops a future date instead of trusting it", () => {
		expect(pageDate([{ resolvedDate: "2031-05-05" }], TODAY)).toEqual({
			date: null,
			reason: "none",
		});
		// One real date and one impossible one leaves exactly one real date.
		expect(
			pageDate(
				[{ resolvedDate: "2024-08-12" }, { resolvedDate: "2031-05-05" }],
				TODAY,
			),
		).toEqual({ date: "2024-08-12", source: "page" });
	});

	it("reports nothing found for a page with no dates", () => {
		expect(pageDate([], TODAY)).toEqual({ date: null, reason: "none" });
	});
});

describe("resolveEntryDate", () => {
	it("prefers the page over the filename when they disagree", () => {
		expect(
			resolveEntryDate({
				mentionedDates: [{ resolvedDate: "2024-08-12" }],
				filename: "2026-01-01.jpg",
				today: TODAY,
			}),
		).toEqual({ date: "2024-08-12", source: "page" });
	});

	it("solves the incident: a dated page inside a camera-named file", () => {
		expect(
			resolveEntryDate({
				mentionedDates: [{ resolvedDate: "2019-04-03" }],
				filename: "IMG_20260925_0001.jpg",
				today: TODAY,
			}),
		).toEqual({ date: "2019-04-03", source: "page" });
	});

	it("falls back to a deliberate filename when the page has no date", () => {
		expect(
			resolveEntryDate({
				mentionedDates: [],
				filename: "2024-08-12.jpg",
				today: TODAY,
			}),
		).toEqual({ date: "2024-08-12", source: "filename" });
	});

	it("uses an explicit filename when the page contradicts itself", () => {
		expect(
			resolveEntryDate({
				mentionedDates: [
					{ resolvedDate: "2024-08-12" },
					{ resolvedDate: "2024-08-14" },
				],
				filename: "2024-08-12.jpg",
				today: TODAY,
			}),
		).toEqual({ date: "2024-08-12", source: "filename" });
	});

	it("reports the page's contradiction when the filename can't settle it", () => {
		expect(
			resolveEntryDate({
				mentionedDates: [
					{ resolvedDate: "2024-08-12" },
					{ resolvedDate: "2024-08-14" },
				],
				filename: "IMG_0001.jpg",
				today: TODAY,
			}),
		).toEqual({ date: null, reason: "ambiguous-page" });
	});

	it("gives up honestly on an undated page in a camera-named file", () => {
		expect(
			resolveEntryDate({
				mentionedDates: [],
				filename: "IMG_20260925_0002.jpg",
				today: TODAY,
			}),
		).toEqual({ date: null, reason: "none" });
	});

	it("never returns a date it wasn't given — no inference from neighbours", () => {
		const result = resolveEntryDate({
			mentionedDates: [],
			filename: "IMG_20260925_0003.jpg",
			today: TODAY,
		});
		expect(result.date).toBeNull();
	});
});

describe("groupConsecutiveByDate", () => {
	const page = (date: string, text: string) => ({ date, text });

	it("returns nothing for no pages", () => {
		expect(groupConsecutiveByDate([])).toEqual([]);
	});

	it("keeps consecutive pages of one day together", () => {
		const pages = [
			page("2024-08-12", "one"),
			page("2024-08-12", "two"),
			page("2024-08-13", "three"),
		];
		expect(groupConsecutiveByDate(pages)).toEqual([
			{ date: "2024-08-12", items: [pages[0], pages[1]] },
			{ date: "2024-08-13", items: [pages[2]] },
		]);
	});

	it("starts a new entry every time the date changes back and forth", () => {
		const pages = [
			page("2024-08-12", "a"),
			page("2024-08-13", "b"),
			page("2024-08-12", "c"),
		];
		expect(groupConsecutiveByDate(pages).map((g) => g.date)).toEqual([
			"2024-08-12",
			"2024-08-13",
			"2024-08-12",
		]);
	});

	it("merges 50 pages into one day only when they really share a date", () => {
		// The shape of the production incident, now only reachable when the
		// pages genuinely carry the same date rather than the same filename.
		const fifty = Array.from({ length: 50 }, (_, i) =>
			page("2024-08-12", `page ${i}`),
		);
		const groups = groupConsecutiveByDate(fifty);
		expect(groups).toHaveLength(1);
		expect(groups[0]?.items).toHaveLength(50);
	});

	it("gives 50 pages of 50 different days 50 entries", () => {
		const fifty = Array.from({ length: 50 }, (_, i) =>
			page(`2024-08-${String(i + 1).padStart(2, "0")}`, `page ${i}`),
		);
		expect(groupConsecutiveByDate(fifty)).toHaveLength(50);
	});
});
