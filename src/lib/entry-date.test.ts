import { describe, expect, it } from "vitest";

import {
	filenameDate,
	groupConsecutiveByDate,
	isoDatesIn,
	isPlausibleEntryDate,
	isRealCalendarDate,
	looksAutoGenerated,
	pageDate,
	parseCasualDate,
	resolveEntryDate,
} from "@/lib/entry-date";

/** Fixed so these tests mean the same thing whenever they run. */
const TODAY = "2026-09-25";

describe("isRealCalendarDate", () => {
	it("accepts real days, including a leap day in a leap year", () => {
		expect(isRealCalendarDate("2024-02-29")).toBe(true);
		expect(isRealCalendarDate("2026-01-01")).toBe(true);
		expect(isRealCalendarDate("2026-12-31")).toBe(true);
	});

	it("rejects days that don't exist", () => {
		expect(isRealCalendarDate("2023-02-29")).toBe(false); // not a leap year
		expect(isRealCalendarDate("2026-02-30")).toBe(false);
		expect(isRealCalendarDate("2026-04-31")).toBe(false);
		expect(isRealCalendarDate("2026-13-01")).toBe(false);
		expect(isRealCalendarDate("2026-00-10")).toBe(false);
		expect(isRealCalendarDate("2026-01-00")).toBe(false);
	});

	it("rejects anything that isn't exactly YYYY-MM-DD", () => {
		expect(isRealCalendarDate("2026-1-1")).toBe(false);
		expect(isRealCalendarDate("26-01-01")).toBe(false);
		expect(isRealCalendarDate("2026/01/01")).toBe(false);
		expect(isRealCalendarDate("")).toBe(false);
	});
});

describe("isPlausibleEntryDate", () => {
	it("accepts today and the past", () => {
		expect(isPlausibleEntryDate(TODAY, TODAY)).toBe(true);
		expect(isPlausibleEntryDate("2019-03-04", TODAY)).toBe(true);
	});

	it("rejects the future — you can't have written it yet", () => {
		expect(isPlausibleEntryDate("2026-09-26", TODAY)).toBe(false);
		expect(isPlausibleEntryDate("2031-01-01", TODAY)).toBe(false);
	});

	it("rejects dates so old they mean we parsed a serial number", () => {
		expect(isPlausibleEntryDate("1899-12-31", TODAY)).toBe(false);
		expect(isPlausibleEntryDate("1900-01-01", TODAY)).toBe(true);
	});
});

describe("isoDatesIn", () => {
	it("finds a date with any of the usual separators", () => {
		expect(isoDatesIn("2024-08-12")).toEqual(["2024-08-12"]);
		expect(isoDatesIn("2024_08_12")).toEqual(["2024-08-12"]);
		expect(isoDatesIn("2024.08.12")).toEqual(["2024-08-12"]);
		expect(isoDatesIn("20240812")).toEqual(["2024-08-12"]);
	});

	it("refuses a match buried inside a longer run of digits", () => {
		// The bug this whole module exists to prevent a repeat of: the old
		// regex had no boundary and happily read a date out of a serial number.
		expect(isoDatesIn("ref1234202408120987")).toEqual([]);
		expect(isoDatesIn("120240812")).toEqual([]);
		expect(isoDatesIn("202408121")).toEqual([]);
	});

	it("finds several, in order", () => {
		expect(isoDatesIn("2024-08-12 to 2024-08-14")).toEqual([
			"2024-08-12",
			"2024-08-14",
		]);
	});

	it("returns nothing when there's nothing to find", () => {
		expect(isoDatesIn("holiday photos")).toEqual([]);
		expect(isoDatesIn("")).toEqual([]);
	});
});

